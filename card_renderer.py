"""可选 Pillow 摘要长图渲染器（支持中文字体自动回退；未安装 Pillow 时优雅返回 None）。"""

from __future__ import annotations

import os
from datetime import datetime
from typing import Any

FONT_CANDIDATES = (
    # Windows 常见中文字体
    r"C:\Windows\Fonts\msyh.ttc",
    r"C:\Windows\Fonts\msyhbd.ttc",
    r"C:\Windows\Fonts\simhei.ttf",
    r"C:\Windows\Fonts\simsun.ttc",
    r"C:\Windows\Fonts\Deng.ttf",
    # Linux 常见中文字体（Ubuntu / Debian / Docker）
    "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
    "/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc",
    "/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc",
    "/usr/share/fonts/truetype/wqy/wqy-microhei.ttc",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
)


def _load_font(image_font_mod: Any, size: int) -> Any:
    for path in FONT_CANDIDATES:
        if os.path.isfile(path):
            try:
                return image_font_mod.truetype(path, size)
            except Exception:
                continue
    return image_font_mod.load_default()


def _wrap_text(text: str, font: Any, max_width: int) -> list[str]:
    """按渲染像素宽度换行，兼容中英文混排。"""
    lines: list[str] = []
    for raw_para in (text or "").splitlines():
        para = raw_para.strip()
        if not para:
            continue
        buf = ""
        for ch in para:
            candidate = buf + ch
            try:
                bbox = font.getbbox(candidate)
                w = bbox[2] - bbox[0]
            except Exception:
                w = len(candidate) * 14
            if w > max_width and buf:
                lines.append(buf)
                buf = ch
            else:
                buf = candidate
        if buf:
            lines.append(buf)
    return lines or [""]


def render_digest_card(
    digest: dict[str, Any],
    output_path: str,
    title: str = "群聊记忆摘要",
) -> str | None:
    """将摘要渲染为 PNG 卡片图并返回文件路径；Pillow 不可用或出错时返回 None。"""
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        return None

    try:
        width = 860
        pad = 40
        content_w = width - pad * 2

        font_title = _load_font(ImageFont, 32)
        font_sub = _load_font(ImageFont, 18)
        font_h = _load_font(ImageFont, 22)
        font_body = _load_font(ImageFont, 19)
        font_foot = _load_font(ImageFont, 15)

        mode_label = "AI 智能摘要" if digest.get("mode") == "llm" else "本地规则摘要"
        date_label = str(digest.get("date") or datetime.now().strftime("%Y-%m-%d"))
        stats_line = (
            f"{date_label}  |  {mode_label}  |  "
            f"消息 {digest.get('message_count', 0)} 条  |  参与 {digest.get('participants', 0)} 人"
        )

        sections: list[tuple[str, list[str]]] = [
            ("核心总览", [str(digest.get("summary") or "暂无摘要")]),
        ]
        topics = digest.get("topics") or []
        if topics:
            sections.append(("热点话题", [" / ".join(str(t) for t in topics[:8])]))
        for heading, key in (
            ("核心精华", "highlights"),
            ("决议共识", "decisions"),
            ("待办线索", "todos"),
            ("收录链接", "links"),
        ):
            vals = digest.get(key) or []
            if vals:
                sections.append(
                    (heading, [f"{i}. {v}" for i, v in enumerate(vals[:6], 1)])
                )

        # 预计算画布高度
        wrapped_sections: list[tuple[str, list[str]]] = []
        y = 148
        for heading, items in sections:
            block_lines: list[str] = []
            for item in items:
                block_lines.extend(_wrap_text(item, font_body, content_w - 36))
            wrapped_sections.append((heading, block_lines))
            y += 38 + len(block_lines) * 29 + 26

        height = max(360, y + 60)
        img = Image.new("RGB", (width, height), (246, 248, 252))
        draw = ImageDraw.Draw(img)

        # 顶部渐变感横幅
        draw.rectangle([(0, 0), (width, 120)], fill=(37, 99, 235))
        draw.text((pad, 26), title, font=font_title, fill=(255, 255, 255))
        draw.text((pad, 76), stats_line, font=font_sub, fill=(219, 234, 254))

        cur_y = 144
        for heading, lines in wrapped_sections:
            card_h = 38 + len(lines) * 29 + 16
            draw.rounded_rectangle(
                [(pad, cur_y), (width - pad, cur_y + card_h)],
                radius=12,
                fill=(255, 255, 255),
                outline=(226, 232, 240),
                width=1,
            )
            draw.rectangle(
                [(pad, cur_y + 12), (pad + 5, cur_y + 34)], fill=(37, 99, 235)
            )
            draw.text((pad + 18, cur_y + 10), heading, font=font_h, fill=(15, 23, 42))
            line_y = cur_y + 44
            for ln in lines:
                draw.text((pad + 18, line_y), ln, font=font_body, fill=(51, 65, 85))
                line_y += 29
            cur_y += card_h + 16

        footer = f"Generated by astrbot_plugin_chat_digest · {datetime.now().strftime('%Y-%m-%d %H:%M')}"
        draw.text((pad, height - 36), footer, font=font_foot, fill=(148, 163, 184))

        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        img.save(output_path, format="PNG")
        return output_path
    except Exception:
        return None
